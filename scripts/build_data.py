def split(v): return [x.strip() for x in v.split('/') if x.strip()] if v else []

def read_raw():
    out = {}
    for p in sorted(glob.glob(os.path.join(ROOT,'raw','*.txt'))):
        t = open(p, encoding='utf-8').read().split('\n')
        h1 = t[0]; m = re.match(r'\[요청 (\d+) / 라운드 (\d+) / 문장 ([ABC])', h1)
        n, r, s = int(m.group(1)), int(m.group(2)), m.group(3)
        blob = '\n'.join(t[:4])
        tm = re.search(r'기록 시각: (\d{4}-\d\d-\d\d \d\d:\d\d)', blob)
        web = re.search(r'웹 검색 표시: ([^\n\(\]]+)', blob)
        pc = re.search(r'PC\d', h1)
        items = [l for l in t if re.match(r'^[1-5]\. ', l)]
        out[n] = dict(file=os.path.basename(p), round=r, s=s, time=tm.group(1) if tm else '', web=web.group(1).strip() if web else '', pc=pc.group(0) if pc else 'PC1', items=items, note_head=h1)
    return out

def main():
    raw = read_raw(); rows = []; problems = []
    assert sorted(raw) == list(range(1,31)), '요청번호 1~30이 모두 있어야 한다'
    for n in range(1,31):
        R = raw[n]; assert len(R['items']) == 5 and len(T[n]) == 5, n
        for i,(line,(c,rg,va,pr,note)) in enumerate(zip(R['items'],T[n]), start=1):
            head = line.split(':')[0] if n == 22 else line   # 22번은 제목 뒤 설명이 같은 줄에 이어짐
            assert head.startswith(f'{i}. '), (n,i)
            for col,val in (('국가',c),('지역',rg),('품종',va),('가공',pr)):
                for x in split(val):
                    key = 'SL28' if x=='SL28' else x
                    if not any(a in head for a in ALIAS[key]): problems.append(f'요청 {n}-{i}: {col} "{x}" 가 제목 줄에 없음: {head}')
            # 거꾸로: 제목 줄에 있는 주요 단어가 기록에서 빠졌는지
            rec = ' / '.join([c,rg,va,pr])
            for key in ['워시드','내추럴','게이샤','핑크 버번','헤이룸','예가체프','구지','시다모','코체레','게뎁','니에리','키암부','키리냐가','우일라','나리뇨','르완다','부룬디','콜롬비아','파나마','케냐']:
                if n==27 and i==2 and key=='내추럴': continue   # "내추럴이 아닌 워시드"라서 내추럴은 기록하지 않음
                if any(a in head for a in ALIAS[key]) and key not in rec and not (key=='게이샤' and '게이샤 빌리지' in rg and not any(a in head.replace('게이샤 빌리지','').replace('게샤 빌리지','') for a in ALIAS['게이샤'])):
                    problems.append(f'요청 {n}-{i}: 제목 줄의 "{key}"가 기록에 없음: {head}')
            rows.append([n,R['round'],R['s'],R['time'],'Claude Sonnet 5.5 (중간)','비공개 대화',R['pc'],i,head.split('. ',1)[1],c,rg,va,pr,'예' if pr else '아니오',R['web'],note,'AI가 원문과 대조함'])
    hdr = ['요청번호','라운드','문장','날짜와 시간','모델','대화 방식','사용 PC','원두 순번','원문 표기','생산국','세부 지역','품종','가공 방식','가공 방식 적힘','웹 검색 표시','비고','분류 확인']
    out = os.path.join(ROOT,'data.csv')
    with open(out,'w',newline='',encoding='utf-8-sig') as f:
        w = csv.writer(f); w.writerow(hdr); w.writerows(rows)
    cnt = {s: sum(1 for r in raw.values() if r['s']==s) for s in 'ABC'}
    print('요청 수', len(raw), '문장별', cnt, '/ 줄 수', len(rows), '/ 원문 파일 수', len(raw))
    print('검사에서 걸린 것:', len(problems))
    for p in problems: print(' ', p)
    return 1 if problems else 0

if __name__ == '__main__':
    sys.exit(main())
